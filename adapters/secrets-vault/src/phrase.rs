//! Generated recovery phrase over the EFF large word list (see `NOTICE`).

use std::fmt;
use std::sync::OnceLock;

use zeroize::Zeroizing;

use crate::VaultError;

pub const DEFAULT_PHRASE_WORDS: usize = 8;
pub const MIN_PHRASE_WORDS: usize = 6;
pub const MAX_PHRASE_WORDS: usize = 40;

/// EFF large word list, verbatim: `<dice index>\t<word>` per line.
const WORDLIST: &str = include_str!("eff_large_wordlist.txt");
const WORD_COUNT: usize = 7776;
/// Largest multiple of `WORD_COUNT` representable in a `u16`. Draws at or
/// above it are rejected so every word is equally likely.
const REJECTION_LIMIT: u16 = (u16::MAX as usize / WORD_COUNT * WORD_COUNT) as u16;

/// Sorted, unique words (pinned by the word-list test).
fn words() -> &'static [&'static str] {
    static WORDS: OnceLock<Vec<&'static str>> = OnceLock::new();
    WORDS.get_or_init(|| {
        WORDLIST
            .lines()
            .filter_map(|line| line.split_once('\t').map(|(_, word)| word))
            .collect()
    })
}

fn check_word_count(count: usize) -> Result<(), VaultError> {
    if (MIN_PHRASE_WORDS..=MAX_PHRASE_WORDS).contains(&count) {
        Ok(())
    } else {
        Err(VaultError::InvalidPhrase)
    }
}

/// Recovery phrase: lowercase list words joined by single spaces. Generated by
/// the vault, never chosen by the operator; shown once.
pub struct RecoveryPhrase(Zeroizing<String>);

impl RecoveryPhrase {
    pub fn generate(word_count: usize) -> Result<Self, VaultError> {
        check_word_count(word_count)?;
        let mut phrase = Zeroizing::new(String::new());
        let mut draw = Zeroizing::new([0_u8; 2]);
        let mut chosen = 0;
        while chosen < word_count {
            getrandom::fill(draw.as_mut()).map_err(|_| VaultError::Unavailable)?;
            let value = u16::from_le_bytes(*draw);
            if value >= REJECTION_LIMIT {
                continue;
            }
            if chosen > 0 {
                phrase.push(' ');
            }
            phrase.push_str(words()[usize::from(value) % WORD_COUNT]);
            chosen += 1;
        }
        Ok(Self(phrase))
    }

    /// Normalizes operator input: case-insensitive, any whitespace between
    /// words. Every word must be on the list.
    pub fn parse(input: &str) -> Result<Self, VaultError> {
        let lowered = Zeroizing::new(input.to_lowercase());
        let mut phrase = Zeroizing::new(String::new());
        let mut count = 0;
        for word in lowered.split_whitespace() {
            if words().binary_search(&word).is_err() {
                return Err(VaultError::InvalidPhrase);
            }
            if count > 0 {
                phrase.push(' ');
            }
            phrase.push_str(word);
            count += 1;
        }
        check_word_count(count)?;
        Ok(Self(phrase))
    }

    /// The phrase text, for the one-time display to the operator.
    pub fn expose(&self) -> &str {
        &self.0
    }

    pub fn word_count(&self) -> usize {
        self.0.split(' ').count()
    }

    pub(crate) fn as_bytes(&self) -> &[u8] {
        self.0.as_bytes()
    }
}

impl fmt::Debug for RecoveryPhrase {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("RecoveryPhrase(..)")
    }
}

#[cfg(test)]
mod tests {
    use sha2::{Digest, Sha256};

    use super::*;

    const EFF_LARGE_WORDLIST_SHA256: &str =
        "addd35536511597a02fa0a9ff1e5284677b8883b83e986e43f15a3db996b903e";

    fn hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }

    #[test]
    fn word_list_is_the_pinned_eff_large_list() {
        assert_eq!(
            hex(&Sha256::digest(WORDLIST.as_bytes())),
            EFF_LARGE_WORDLIST_SHA256
        );
        assert_eq!(words().len(), WORD_COUNT);
        assert!(words().windows(2).all(|pair| pair[0] < pair[1]));
    }

    #[test]
    fn rejection_limit_is_the_largest_unbiased_bound() {
        assert_eq!(usize::from(REJECTION_LIMIT) % WORD_COUNT, 0);
        assert!(usize::from(REJECTION_LIMIT) + WORD_COUNT > usize::from(u16::MAX));
    }

    #[test]
    fn generate_enforces_word_count_bounds() {
        for count in [0, MIN_PHRASE_WORDS - 1, MAX_PHRASE_WORDS + 1] {
            assert_eq!(
                RecoveryPhrase::generate(count).unwrap_err(),
                VaultError::InvalidPhrase
            );
        }
        for count in [MIN_PHRASE_WORDS, DEFAULT_PHRASE_WORDS, MAX_PHRASE_WORDS] {
            assert_eq!(RecoveryPhrase::generate(count).unwrap().word_count(), count);
        }
    }

    #[test]
    fn generated_words_come_from_the_list_and_differ_between_phrases() {
        let first = RecoveryPhrase::generate(DEFAULT_PHRASE_WORDS).unwrap();
        let second = RecoveryPhrase::generate(DEFAULT_PHRASE_WORDS).unwrap();
        assert!(first
            .expose()
            .split(' ')
            .all(|word| words().binary_search(&word).is_ok()));
        assert_ne!(first.expose(), second.expose());
    }

    #[test]
    fn parse_normalizes_case_and_whitespace() {
        let phrase =
            RecoveryPhrase::parse("  Abacus\tABDOMEN  abdominal\nabide abiding ability ").unwrap();
        assert_eq!(
            phrase.expose(),
            "abacus abdomen abdominal abide abiding ability"
        );
    }

    #[test]
    fn parse_round_trips_a_generated_phrase() {
        let generated = RecoveryPhrase::generate(DEFAULT_PHRASE_WORDS).unwrap();
        let parsed = RecoveryPhrase::parse(generated.expose()).unwrap();
        assert_eq!(parsed.as_bytes(), generated.as_bytes());
    }

    #[test]
    fn parse_rejects_unknown_words_and_bad_counts() {
        let inputs = [
            "abacus abdomen abdominal abide abiding notaword",
            "abacus abdomen abdominal abide abiding",
            &"abacus ".repeat(MAX_PHRASE_WORDS + 1),
            "",
        ];
        for input in inputs {
            assert_eq!(
                RecoveryPhrase::parse(input).unwrap_err(),
                VaultError::InvalidPhrase
            );
        }
    }

    #[test]
    fn phrase_debug_never_renders_words() {
        let phrase = RecoveryPhrase::generate(DEFAULT_PHRASE_WORDS).unwrap();
        assert_eq!(format!("{phrase:?}"), "RecoveryPhrase(..)");
    }
}
