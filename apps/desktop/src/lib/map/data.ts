import raw from "./maps.generated.json";

export interface Point {
  x: number;
  y: number;
}

export interface CapNode {
  id: string;
  title: string;
  summary: string;
  crates: string[];
  confidence: number;
  validated: boolean;
  x: number;
  y: number;
  w: number;
  h: number;
}

export interface RoutedEdge {
  from: string;
  to: string;
  points: Point[];
}

export interface TaskNode {
  id: string;
  state: "done" | "ready" | "wait";
  x: number;
  y: number;
  w: number;
  h: number;
}

interface MapData {
  crates: Array<{ name: string; path: string; capability: string | null }>;
  crateEdges: Array<[string, string]>;
  capabilityEdgesAll: Array<[string, string]>;
  map: { width: number; height: number; nodes: CapNode[]; edges: RoutedEdge[] };
  g15: { width: number; height: number; critical: string[]; nodes: TaskNode[]; edges: Array<RoutedEdge & { kind: "done" | "main" | "side" }> };
}

/** Generated by scripts/gen-maps.ts from cargo metadata, queue.yaml and capabilities.ts. */
export const MAPS = raw as unknown as MapData;

/** Orthogonal polyline with rounded bends. */
export function roundedPath(points: Point[], radius = 8): string {
  if (points.length < 2) return "";
  let d = `M${points[0].x},${points[0].y}`;
  for (let i = 1; i < points.length - 1; i += 1) {
    const [a, b, c] = [points[i - 1], points[i], points[i + 1]];
    const inLen = Math.hypot(b.x - a.x, b.y - a.y);
    const outLen = Math.hypot(c.x - b.x, c.y - b.y);
    const r = Math.min(radius, inLen / 2, outLen / 2);
    const p1 = { x: b.x - ((b.x - a.x) / (inLen || 1)) * r, y: b.y - ((b.y - a.y) / (inLen || 1)) * r };
    const p2 = { x: b.x + ((c.x - b.x) / (outLen || 1)) * r, y: b.y + ((c.y - b.y) / (outLen || 1)) * r };
    d += ` L${p1.x},${p1.y} Q${b.x},${b.y} ${p2.x},${p2.y}`;
  }
  const last = points[points.length - 1];
  return `${d} L${last.x},${last.y}`;
}

function closure(start: string, next: (id: string) => string[]): string[] {
  const seen = new Set<string>();
  const stack = next(start);
  while (stack.length) {
    const id = stack.pop() as string;
    if (seen.has(id)) continue;
    seen.add(id);
    stack.push(...next(id));
  }
  return [...seen].sort();
}

const crateDependents = (name: string): string[] => MAPS.crateEdges.filter(([, to]) => to === name).map(([from]) => from);
const crateDependencies = (name: string): string[] => MAPS.crateEdges.filter(([from]) => from === name).map(([, to]) => to);
const capDependents = (id: string): string[] => MAPS.capabilityEdgesAll.filter(([, to]) => to === id).map(([from]) => from);
const capDependencies = (id: string): string[] => MAPS.capabilityEdgesAll.filter(([from]) => from === id).map(([, to]) => to);

export const capabilityOf = (crate: string): string | null => MAPS.crates.find((c) => c.name === crate)?.capability ?? null;
export const cratePath = (crate: string): string => MAPS.crates.find((c) => c.name === crate)?.path ?? "";
export const capTitle = (id: string): string => MAPS.map.nodes.find((n) => n.id === id)?.title ?? id;

export interface CrateFacts {
  dependsOn: string[];
  directDependents: string[];
  affected: string[];
}

/** What a change in this crate reaches: direct and transitive dependents (cargo metadata). */
export function crateFacts(name: string): CrateFacts {
  return { dependsOn: crateDependencies(name).sort(), directDependents: crateDependents(name).sort(), affected: closure(name, crateDependents) };
}

export interface CapFacts {
  dependsOn: string[];
  affected: string[];
}

export function capFacts(id: string): CapFacts {
  return { dependsOn: capDependencies(id).sort(), affected: closure(id, capDependents) };
}

export type Selection = { kind: "cap"; id: string } | { kind: "crate"; name: string } | null;

export interface Highlight {
  caps: Set<string>;
  crates: Set<string>;
  primaryCap: string | null;
}

/** Capability selection: neighbours within two hops on the drawn graph. Crate selection: everything it affects. */
export function highlight(selection: Selection): Highlight | null {
  if (!selection) return null;
  if (selection.kind === "crate") {
    const affected = crateFacts(selection.name).affected;
    const caps = new Set([selection.name, ...affected].map((c) => capabilityOf(c)).filter((c): c is string => c !== null));
    return { caps, crates: new Set(affected), primaryCap: capabilityOf(selection.name) };
  }
  const caps = new Set([selection.id]);
  let frontier = [selection.id];
  for (let hop = 0; hop < 2; hop += 1) {
    frontier = MAPS.map.edges
      .flatMap((e) => (frontier.includes(e.from) ? [e.to] : frontier.includes(e.to) ? [e.from] : []))
      .filter((id) => !caps.has(id));
    frontier.forEach((id) => caps.add(id));
  }
  return { caps, crates: new Set(), primaryCap: selection.id };
}
